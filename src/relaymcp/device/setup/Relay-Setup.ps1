function Get-HomeGateways {
    @(Get-Content (Join-Path $Kit 'home-gateways.txt') -ErrorAction SilentlyContinue |
        ForEach-Object { $_.Trim().ToUpper().Replace(':', '-') } |
        Where-Object { $_ -match '^([0-9A-F]{2}-){5}[0-9A-F]{2}$' })
}

# One entry per connected IPv4 default gateway, with the router's MAC freshly confirmed on that interface.
# A stale cache entry left over from another network is never trusted.
function Get-Gateways {
    $routes = @(Get-NetRoute -AddressFamily IPv4 -DestinationPrefix '0.0.0.0/0' -ErrorAction SilentlyContinue | Where-Object { $_.NextHop -and $_.NextHop -ne '0.0.0.0' })
    foreach ($route in $routes) {
        $ifIndex = $route.InterfaceIndex
        $gateway = $route.NextHop
        $neighbor = Get-NetNeighbor -AddressFamily IPv4 -InterfaceIndex $ifIndex -IPAddress $gateway -ErrorAction SilentlyContinue
        if (-not $neighbor -or $neighbor.State -ne 'Reachable') {
            Remove-NetNeighbor -InterfaceIndex $ifIndex -IPAddress $gateway -Confirm:$false -ErrorAction SilentlyContinue
            try { [void](New-Object System.Net.NetworkInformation.Ping).Send($gateway, 1000) } catch { }
            for ($i = 0; $i -lt 12; $i++) {
                $neighbor = Get-NetNeighbor -AddressFamily IPv4 -InterfaceIndex $ifIndex -IPAddress $gateway -ErrorAction SilentlyContinue
                if ($neighbor -and $neighbor.State -eq 'Reachable') { break }
                Start-Sleep -Milliseconds 250
            }
        }
        if ($neighbor -and $neighbor.State -eq 'Reachable') {
            $netProfile = Get-NetConnectionProfile -InterfaceIndex $ifIndex -ErrorAction SilentlyContinue | Select-Object -First 1
            [pscustomobject]@{
                InterfaceIndex = $ifIndex
                Mac            = $neighbor.LinkLayerAddress.ToUpper()
                Network        = [string]$netProfile.Name
                Category       = [string]$netProfile.NetworkCategory
            }
        }
    }
}

# Stops the RelayMCP agent (Windows-MCP, hardware server, keep-awake) and anything left over from it. Apps that the AI
# agent opened are not touched. Returns $true if anything was running.
function Stop-Agent {
    $wasRunning = [bool](Get-NetTCPConnection -LocalPort $ScreenPort, $HardwarePort -State Listen -ErrorAction SilentlyContinue)
    $task = Get-ScheduledTask -TaskName 'RelayMCP-Agent' -ErrorAction SilentlyContinue
    if ($task -and "$($task.State)" -eq 'Running') { Stop-ScheduledTask -TaskName 'RelayMCP-Agent'; $wasRunning = $true }
    $patterns = @('relaymcp\.device\.(agent|server)', ('windows_mcp serve .*--port ' + $ScreenPort))
    $procs = @(Get-CimInstance Win32_Process -Filter "Name='python.exe' OR Name='pythonw.exe'" |
        Where-Object { $cmd = ([string]$_.CommandLine) -replace '\s+', ' '; @($patterns | Where-Object { $cmd -match $_ }).Count })
    foreach ($p in $procs) { Stop-Process -Id $p.ProcessId -Force -ErrorAction SilentlyContinue; $wasRunning = $true }
    return $wasRunning
}

