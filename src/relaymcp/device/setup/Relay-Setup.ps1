    if ($homeNets.Count) {
        $mode = 'home'
        $reason = "on home network '$($homeNets[0].Network)'"
    } elseif ($gateways.Count) {
        # On some other network: switch off right away.
        $mode = 'away'
        $reason = "on another network ('$($gateways[0].Network)')"
    } else {
        # No network at all (asleep, Wi-Fi blip, airplane mode): nothing can reach the handheld, so don't churn.
        # Stay as-is for 10 minutes, then switch off.
        $since = $null
        try { $since = [datetime](Get-Content $offlineFile -ErrorAction Stop | Select-Object -First 1) } catch { }
        if (-not $since) { $since = Get-Date; Set-Content -Path $offlineFile -Value $since.ToString('o') -Encoding ascii }
        $mode = if ($previous -eq 'home' -and ((Get-Date) - $since).TotalMinutes -lt 10) { 'home' } else { 'away' }
        $reason = 'offline for 10+ minutes'
    }
    if ($gateways.Count) { Remove-Item -Path $offlineFile -Force -ErrorAction SilentlyContinue }
    if ($mode -ne $previous) {
        Set-Content -Path $stateFile -Value $mode -Encoding ascii
        $changes.Add($reason)
    }

    # SSH firewall rules: Private networks and the local subnet only (defense in depth; affects nothing else).
    if (-not (Get-NetFirewallRule -Name 'OpenSSH-Server-In-TCP' -ErrorAction SilentlyContinue)) {
        New-NetFirewallRule -Name 'OpenSSH-Server-In-TCP' -DisplayName 'OpenSSH SSH Server (sshd)' -Direction Inbound -Protocol TCP -LocalPort 22 -Action Allow -Profile Private -RemoteAddress LocalSubnet | Out-Null
        $changes.Add('re-created the SSH firewall rule')
    }
    foreach ($rule in @(Get-NetFirewallRule -Direction Inbound | Where-Object { $_.Name -like '*OpenSSH*' -or $_.DisplayName -like '*sshd*' })) {
        $scope = ($rule | Get-NetFirewallAddressFilter).RemoteAddress
        if ("$($rule.Enabled)" -ne 'True' -or "$($rule.Profile)" -ne 'Private' -or "$scope" -ne 'LocalSubnet') {
            $rule | Set-NetFirewallRule -Enabled True -Profile Private -RemoteAddress LocalSubnet
            $changes.Add("re-scoped firewall rule '$($rule.DisplayName)'")
        }
    }

    # sshd stays registered on Manual start; this task decides when it runs.
    $exe = Join-Path $env:ProgramFiles 'OpenSSH\sshd.exe'
    $svc = Get-CimInstance Win32_Service -Filter "Name='sshd'"
    if (-not $svc -and (Test-Path $exe)) {
        New-Service -Name sshd -DisplayName 'OpenSSH SSH Server' -BinaryPathName ('"' + $exe + '"') -StartupType Manual | Out-Null
        $changes.Add('re-registered the missing sshd service')
    } elseif ($svc -and -not (Test-Path $svc.PathName.Trim('"')) -and (Test-Path $exe)) {
        Set-ItemProperty -Path 'HKLM:\SYSTEM\CurrentControlSet\Services\sshd' -Name ImagePath -Value ('"' + $exe + '"')
        $changes.Add("repointed sshd to $exe")
    }
    $sshd = Get-Service -Name sshd -ErrorAction SilentlyContinue
    if ($sshd -and "$($sshd.StartType)" -ne 'Manual') {
        Set-Service -Name sshd -StartupType Manual
        $changes.Add("sshd start type $($sshd.StartType) -> Manual")
    }

    if ($mode -eq 'home') {
        foreach ($net in $homeNets) {
            if ($net.Category -eq 'Public') {
                Set-NetConnectionProfile -InterfaceIndex $net.InterfaceIndex -NetworkCategory Private
                $changes.Add("home network '$($net.Network)' was Public; set to Private")
            }
        }
        if ($sshd -and "$($sshd.Status)" -ne 'Running') { Start-Service -Name sshd; $changes.Add('started SSH') }
        if ((Get-CimInstance Win32_ComputerSystem).UserName) {
            # The agent restarts its own servers if they exit; this only (re)starts the agent itself.
            $agentTask = Get-ScheduledTask -TaskName 'RelayMCP-Agent' -ErrorAction SilentlyContinue
            if ($agentTask -and "$($agentTask.State)" -ne 'Running') {
                Start-ScheduledTask -TaskName 'RelayMCP-Agent'
                $changes.Add('started the RelayMCP agent (Windows-MCP, hardware server, keep-awake)')
            }
        }
    } else {
        if ($sshd -and "$($sshd.Status)" -ne 'Stopped') { Stop-Service -Name sshd -Force; $changes.Add('stopped SSH') }
        if (Stop-Agent) { $changes.Add('stopped the RelayMCP agent') }
    }
} catch {
    $changes.Add("error: $($_.Exception.Message)")
}
if ($changes.Count) { "$(Get-Date -Format s) [$mode] $($changes -join '; ')" | Add-Content -Path $ControllerLog }
'@

function Step([string]$Message) { Write-Host "==> $Message" -ForegroundColor Cyan }
function Info([string]$Message) { Write-Host "    $Message" }

function Invoke-Icacls([string[]]$Arguments) {
    & icacls.exe @Arguments | Out-Null
    if ($LASTEXITCODE -ne 0) { throw "icacls $($Arguments -join ' ') failed ($LASTEXITCODE)" }
}

function Restart-SshdSafely {
    # A one-off SYSTEM task restarts sshd, so an SSH session running this script can't cut the restart short.
    $action = New-ScheduledTaskAction -Execute 'powershell.exe' -Argument '-NoProfile -WindowStyle Hidden -Command "Start-Sleep -Seconds 2; Restart-Service sshd"'
    Register-ScheduledTask -TaskName 'RelayMCP-RestartSshd' -Action $action -User 'SYSTEM' -RunLevel Highest -Force | Out-Null
    Start-ScheduledTask -TaskName 'RelayMCP-RestartSshd'
}

function Show-Result([string]$Text, [bool]$Ok) {
    if ($Unattended) { return }
    Add-Type -AssemblyName System.Windows.Forms
    $owner = New-Object System.Windows.Forms.Form -Property @{ TopMost = $true }
    $icon = if ($Ok) { [System.Windows.Forms.MessageBoxIcon]::Information } else { [System.Windows.Forms.MessageBoxIcon]::Error }
    [System.Windows.Forms.MessageBox]::Show($owner, $Text, 'RelayMCP', [System.Windows.Forms.MessageBoxButtons]::OK, $icon) | Out-Null
}

function Read-YesNo([string]$Text) {
    if ($Unattended) { return $false }
    Add-Type -AssemblyName System.Windows.Forms
    $owner = New-Object System.Windows.Forms.Form -Property @{ TopMost = $true }
    $answer = [System.Windows.Forms.MessageBox]::Show($owner, $Text, 'RelayMCP', [System.Windows.Forms.MessageBoxButtons]::YesNo, [System.Windows.Forms.MessageBoxIcon]::Question)
    return ($answer -eq [System.Windows.Forms.DialogResult]::Yes)
}

# Only ever called while on the home network, so status never goes to a device on some other network.
function Send-Report([System.Collections.IDictionary]$Fields) {
    $query = ($Fields.GetEnumerator() | ForEach-Object { '{0}={1}' -f $_.Key, [uri]::EscapeDataString([string]$_.Value) }) -join '&'
    foreach ($url in $ReportUrls) {
        try { Invoke-RestMethod -Uri ('{0}?{1}' -f $url, $query) -TimeoutSec 4 | Out-Null; return } catch { }
    }
}

# Removes RelayMCP from this handheld. OpenSSH Server and the ViGEmBus driver stay installed (remove them in
# Settings > Apps if you like); SSH is stopped and disabled, and this computer's key is removed.
function Invoke-Uninstall {
    Step 'Removing RelayMCP'
    $libFile = Join-Path $KitDir 'controller.ps1'
    if (Test-Path $libFile) { . $libFile -LibraryOnly; [void](Stop-Agent) }
    foreach ($t in @(Get-ScheduledTask -ErrorAction SilentlyContinue | Where-Object { $_.TaskName -like 'RelayMCP-*' })) {
        if ("$($t.State)" -eq 'Running') { Stop-ScheduledTask -TaskName $t.TaskName -ErrorAction SilentlyContinue }
        Unregister-ScheduledTask -TaskName $t.TaskName -Confirm:$false
        Info "removed task $($t.TaskName)"
    }
    foreach ($lnk in @((Join-Path ([Environment]::GetFolderPath('Desktop')) 'Repair RelayMCP.lnk'),
                       (Join-Path ([Environment]::GetFolderPath('CommonPrograms')) 'Repair RelayMCP.lnk'),
                       (Join-Path ([Environment]::GetFolderPath('Desktop')) 'Ask Copilot.lnk'),
                       (Join-Path ([Environment]::GetFolderPath('Programs')) 'Ask Copilot.lnk'))) {
        Remove-Item -Path $lnk -Force -ErrorAction SilentlyContinue
    }
    $env:Path = "$(Join-Path $env:USERPROFILE '.local\bin');$env:Path"
    if (Get-Command uv -ErrorAction SilentlyContinue) {
        foreach ($tool in @('relaymcp-device', 'windows-mcp')) { cmd /c "uv tool uninstall $tool 2>&1" | Out-Null }
        Info 'uninstalled the RelayMCP device runtime and Windows-MCP'
    }
    Remove-Item -Recurse -Force -Path (Join-Path $env:LOCALAPPDATA 'RelayMCP') -ErrorAction SilentlyContinue
    $keysFile = Join-Path $SshDir 'administrators_authorized_keys'
    if (Test-Path $keysFile) {
        $keep = @(Get-Content $keysFile | Where-Object { $_.Trim() -and ($AuthorizedKeys -notcontains $_) })
        if ($keep.Count) { Set-Content -Path $keysFile -Value $keep -Encoding ascii } else { Remove-Item $keysFile -Force }
        Info "removed $HostLabel's SSH key"
    }
    Set-Location $env:SystemRoot
    Remove-Item -Recurse -Force -Path $KitDir -ErrorAction SilentlyContinue
    $msg = "RelayMCP was removed from this handheld.`n`nOpenSSH Server and the Nefarius ViGEmBus driver are still installed " +
        "(SSH is stopped and disabled); remove them in Settings > Apps if you like."
    Write-Host $msg -ForegroundColor Green
    Show-Result $msg $true
    # Last, because it ends an SSH session that may be running this very uninstall.
    Remove-NetFirewallRule -Name 'OpenSSH-Server-In-TCP' -ErrorAction SilentlyContinue
    if (Get-Service -Name sshd -ErrorAction SilentlyContinue) {
        Set-Service -Name sshd -StartupType Disabled
        Stop-Service -Name sshd -Force -ErrorAction SilentlyContinue
    }
}

if ($Uninstall) {
    try { Invoke-Uninstall } catch { Write-Host "Uninstall failed: $($_.Exception.Message)" -ForegroundColor Red; Show-Result "Uninstall hit a problem:`n`n$($_.Exception.Message)" $false }
    return
}

