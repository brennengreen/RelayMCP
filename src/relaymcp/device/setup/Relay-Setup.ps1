        Start-Service -Name sshd
        for ($i = 0; ($i -lt 30) -and -not (Test-Path $cfg); $i++) { Start-Sleep -Milliseconds 500 }
        if (-not $atHome) { Stop-Service -Name sshd -Force }
    }
    if (-not (Test-Path $cfg)) { throw 'sshd did not create its config file.' }
    $keysFile = Join-Path $SshDir 'administrators_authorized_keys'
    $keys = @()
    if (Test-Path $keysFile) { $keys = @(Get-Content $keysFile | Where-Object { $_.Trim() }) }
    $missing = @($AuthorizedKeys | Where-Object { $keys -notcontains $_ })
    if ($missing.Count) {
        Set-Content -Path $keysFile -Value ($keys + $missing) -Encoding ascii
        Info "authorized $($missing.Count) new key(s)"
    }
    Invoke-Icacls @($keysFile, '/inheritance:r', '/grant', '*S-1-5-32-544:F', '/grant', '*S-1-5-18:F', '/Q')
