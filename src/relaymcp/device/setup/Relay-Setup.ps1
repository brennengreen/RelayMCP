$changes = New-Object System.Collections.Generic.List[string]
try {
    if ((Test-Path $ControllerLog) -and (Get-Item $ControllerLog).Length -gt 256KB) {
        Set-Content -Path $ControllerLog -Value (Get-Content $ControllerLog -Tail 200)
    }
