$Controller = @'
# RelayMCP controller: runs as SYSTEM at boot, at login, when a network connects or disconnects, and every 15 minutes.
#   At home (the router's MAC is listed in home-gateways.txt): keeps SSH and the RelayMCP agent running; repairs them.
#   On any other network: stops both right away. Offline: leaves things as they are for 10 minutes (so sleep and
#   Wi-Fi blips don't churn), then stops both. It never changes any other network's settings.
