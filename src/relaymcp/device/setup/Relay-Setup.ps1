    $sftpExe = Join-Path (Split-Path $sshdPath) 'sftp-server.exe'
    if (Test-Path $sftpExe) {
        $sftpShort = (New-Object -ComObject Scripting.FileSystemObject).GetFile($sftpExe).ShortPath
        if ($sftpShort -notmatch ' ') {
            $new = @($new -replace '^\s*Subsystem\s+sftp\s+.*$', "Subsystem sftp $sftpShort")
            if (-not ($new -match '^Subsystem\s+sftp\s')) { $new = @("Subsystem sftp $sftpShort") + $new }
        } else {
            $sftpDir = Split-Path $sftpExe
            $machinePath = [Environment]::GetEnvironmentVariable('Path', 'Machine')
            if (($machinePath -split ';') -notcontains $sftpDir) {
                [Environment]::SetEnvironmentVariable('Path', "$machinePath;$sftpDir", 'Machine')
                Info 'added OpenSSH to PATH for SFTP (takes effect after a restart)'
            }
        }
    }
    if (-not ($new -match '^PasswordAuthentication no$')) { $new = @('PasswordAuthentication no') + $new }
    if (-not ($new -match '^KbdInteractiveAuthentication no$')) { $new = @('KbdInteractiveAuthentication no') + $new }
    # Drop dead sessions within about a minute, so a Wi-Fi blip can't leave a stale session holding the voice
    # tunnel's port (127.0.0.1:$VoicePort) and block the reconnect.
    $new = @($new | Where-Object { $_ -notmatch '^\s*#?\s*ClientAlive(Interval|CountMax)\s' })
    $new = @('ClientAliveInterval 15', 'ClientAliveCountMax 4') + $new
    if (($orig -join "`n") -ne ($new -join "`n")) {
        Copy-Item -Path $cfg -Destination "$cfg.bak-relaymcp" -Force
        Set-Content -Path $cfg -Value $new -Encoding ascii
        & $sshdPath -t
        if ($LASTEXITCODE -ne 0) {
            Copy-Item -Path "$cfg.bak-relaymcp" -Destination $cfg -Force
            throw 'sshd_config failed validation; restored the backup.'
        }
        Info 'sshd_config updated (key-only logins, SFTP path, dead-session timeout)'
        if ((Get-Service -Name sshd).Status -eq 'Running') { Restart-SshdSafely }
    }
    if (-not (Test-Path 'HKLM:\SOFTWARE\OpenSSH')) { New-Item -Path 'HKLM:\SOFTWARE\OpenSSH' | Out-Null }
    New-ItemProperty -Path 'HKLM:\SOFTWARE\OpenSSH' -Name DefaultShell -PropertyType String -Force -Value "$env:SystemRoot\System32\WindowsPowerShell\v1.0\powershell.exe" | Out-Null

    Step 'Windows-MCP (screen control, runs hidden)'
    $bin = Join-Path $env:USERPROFILE '.local\bin'
    $env:Path = "$bin;$env:Path"
    if (-not (Test-Path (Join-Path $bin 'uv.exe'))) {
        Info 'installing uv...'
        Invoke-RestMethod -Uri 'https://astral.sh/uv/install.ps1' | Invoke-Expression | Out-Null
    }
    $toolList = [string](cmd /c 'uv tool list 2>nul')
    $wmVersion = ($WindowsMcpSpec -split '==')[1]
    if (-not ($toolList -match 'windows-mcp v') -or ($wmVersion -and -not ($toolList -match ('windows-mcp v' + [regex]::Escape($wmVersion) + '\b')))) {
        Info "installing Windows-MCP ($WindowsMcpSpec; the first run downloads Python, 1-2 minutes)..."
        [void](Stop-Agent)
        $out = cmd /c "uv tool install --force $WindowsMcpSpec 2>&1"
        if ($LASTEXITCODE -ne 0) { throw "Installing Windows-MCP failed: $(($out | Select-Object -Last 2) -join ' ')" }
    }
    $toolDir = [string](cmd /c 'uv tool dir 2>nul' | Select-Object -First 1)
    $mcpPython = Join-Path $toolDir.Trim() 'windows-mcp\Scripts\python.exe'
    if (-not (Test-Path $mcpPython)) { throw "Windows-MCP's Python wasn't found at $mcpPython." }

    Step 'Virtual gamepad driver (ViGEmBus)'
    # Must come before the runtime: building vgamepad (the driver's Python wrapper) on a machine without the driver
    # opens the driver's interactive installer and waits for clicks. Installed silently here instead, from the kit's
    # copy, after checking the publisher's signature.
    $vigemRegistered = [bool](Get-ChildItem 'HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall' -ErrorAction SilentlyContinue |
        Get-ItemProperty -ErrorAction SilentlyContinue | Where-Object { $_.DisplayName -like 'Nefarius Virtual Gamepad Emulation Bus Driver*' })
    $vigemPresent = [bool](Get-PnpDevice -FriendlyName '*Virtual Gamepad Emulation Bus*' -PresentOnly -ErrorAction SilentlyContinue)
    if ($vigemRegistered -and $vigemPresent) {
        Info 'already installed'
    } else {
        $vigem = Join-Path $KitDir 'ViGEmBusSetup_x64.msi'
        if (-not (Test-Path $vigem)) { throw 'ViGEmBusSetup_x64.msi is missing from this kit. Rebuild it with `relaymcp kit`.' }
        $sig = Get-AuthenticodeSignature -FilePath $vigem
        if ($sig.Status -ne 'Valid' -or $sig.SignerCertificate.Subject -notmatch 'Nefarius') { throw "The ViGEmBus installer's signature isn't valid ($($sig.Status))." }
        Info 'installing the virtual gamepad driver (about 20 seconds)...'
        $p = Start-Process msiexec.exe -ArgumentList "/i `"$vigem`" /qn /norestart /l*v `"$(Join-Path $KitDir 'vigembus-install.log')`"" -Wait -PassThru
        if ($p.ExitCode -notin 0, 3010) { throw "The ViGEmBus installer failed (exit code $($p.ExitCode)); see vigembus-install.log." }
    }

    Step 'RelayMCP device runtime (hardware tools, voice; runs hidden)'
    $hhZip = Join-Path $KitDir 'relaymcp-device.zip'
    $hhDir = Join-Path $KitDir 'device'
    $hhVenv = Join-Path $toolDir.Trim() 'relaymcp-device'
    $hhExe = Join-Path $hhVenv 'Scripts\relaymcp-device.exe'
    $hhInstalled = $false
    if (Test-Path $hhZip) {
        $hhHash = (Get-FileHash -Path $hhZip -Algorithm SHA256).Hash
        $hashFile = Join-Path $KitDir 'relaymcp-device.sha256'
        $current = [string](Get-Content $hashFile -ErrorAction SilentlyContinue | Select-Object -First 1)
        if ($current -ne $hhHash -or -not (Test-Path $hhExe)) {
            Info 'installing the device runtime (the first time downloads Python 3.12 and speech libraries)...'
            [void](Stop-Agent)
            Remove-Item -Recurse -Force $hhDir -ErrorAction SilentlyContinue
            Expand-Archive -Path $hhZip -DestinationPath $hhDir -Force
            $out = cmd /c "uv tool install --force --reinstall-package relaymcp-device --python 3.12 `"$hhDir`" 2>&1"
            if ($LASTEXITCODE -ne 0) { throw "Installing the device runtime failed: $(($out | Select-Object -Last 3) -join ' ')" }
            Set-Content -Path $hashFile -Value $hhHash -Encoding ascii
        }
        $hhInstalled = Test-Path $hhExe
        if ($hhInstalled) {
            # Natural voice for spoken replies (~200 MB, first time only; hash-checked). Optional: without it the
            # Windows voice is used.
            $hhPython = Join-Path $hhVenv 'Scripts\python.exe'
            $voiceOut = cmd /c "`"$hhPython`" -m relaymcp.device.tts --download 2>&1"
            if ($LASTEXITCODE -ne 0) { Info "natural voice not downloaded yet (using the Windows voice): $(($voiceOut | Select-Object -Last 1))" }
            elseif ("$voiceOut" -match 'downloading') { Info 'downloaded the natural voice' }
        }
    } else {
        throw 'relaymcp-device.zip is missing from this kit. Rebuild it with `relaymcp kit`.'
    }
    if ($hhInstalled) {
        # Fixed-action SYSTEM task that closes Armoury Crate's "External controller connected" notice (an elevated
        # window the non-elevated server can't click) without choosing anything. Standard users may run only this task.
        $service = New-Object -ComObject Schedule.Service
        $service.Connect()
        $def = $service.NewTask(0)
        $def.RegistrationInfo.Description = "Closes Armoury Crate's external-controller notice raised by RelayMCP's virtual gamepad. Fixed action; see C:\ProgramData\RelayMCP."
        $def.Settings.DisallowStartIfOnBatteries = $false
        $def.Settings.StopIfGoingOnBatteries = $false
        $def.Settings.ExecutionTimeLimit = 'PT1M'
        $def.Settings.MultipleInstances = 2
        $def.Principal.UserId = 'SYSTEM'
        $def.Principal.LogonType = 5
        $def.Principal.RunLevel = 1
        $a = $def.Actions.Create(0)
        $a.Path = "$env:SystemRoot\System32\WindowsPowerShell\v1.0\powershell.exe"
        $a.Arguments = '-NoProfile -NonInteractive -WindowStyle Hidden -Command "Get-Process -Name ExternalControllerHelper -ErrorAction SilentlyContinue | Stop-Process -Force; exit 0"'
        [void]$service.GetFolder('\').RegisterTaskDefinition('RelayMCP-DismissControllerNotice', $def, 6, 'SYSTEM', $null, 5, 'D:(A;;FA;;;SY)(A;;FA;;;BA)(A;;GRGX;;;AU)')
    }

    Step 'RelayMCP agent (runs Windows-MCP and the hardware server hidden; keeps the handheld awake while in use)'
    # pythonw.exe: no window and no console. The agent starts each server with a hidden console, restarts them if they
    # exit, and ends them when it stops. RelayMCP-Controller starts it only at home and stops it everywhere else.
    $agentPython = Join-Path $hhVenv 'Scripts\pythonw.exe'
    if (-not $hhInstalled -or -not (Test-Path $agentPython)) { throw "The device runtime didn't install, so the RelayMCP agent can't run." }
    $agentAction = New-ScheduledTaskAction -Execute $agentPython -Argument '-m relaymcp.device.agent' -WorkingDirectory $env:LOCALAPPDATA
    $agentPrincipal = New-ScheduledTaskPrincipal -UserId ([Security.Principal.WindowsIdentity]::GetCurrent().Name) -LogonType Interactive -RunLevel Limited
    $agentSettings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -MultipleInstances IgnoreNew -ExecutionTimeLimit ([TimeSpan]::Zero) -Priority 5
    Register-ScheduledTask -TaskName 'RelayMCP-Agent' -Description 'RelayMCP: runs Windows-MCP (screen control) and the hardware server hidden, and keeps the handheld awake while an AI agent uses it. No triggers: RelayMCP-Controller starts it only while at home. See C:\ProgramData\RelayMCP.' -Action $agentAction -Principal $agentPrincipal -Settings $agentSettings -Force | Out-Null
    [void](Stop-Agent)  # the controller starts it again with the current version

    Step 'Controller task (remote access on at home, off everywhere else)'
    $taskAction = New-ScheduledTaskAction -Execute 'powershell.exe' -Argument ('-NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File "' + $controllerFile + '"')
    $atBoot = New-ScheduledTaskTrigger -AtStartup
    $atBoot.Delay = 'PT30S'
    $atLogon = New-ScheduledTaskTrigger -AtLogOn
    $atLogon.Delay = 'PT20S'
    $every15 = New-ScheduledTaskTrigger -Once -At (Get-Date).AddMinutes(1) -RepetitionInterval (New-TimeSpan -Minutes 15)
    $eventClass = Get-CimClass -Namespace 'Root/Microsoft/Windows/TaskScheduler' -ClassName 'MSFT_TaskEventTrigger'
    $onNetwork = New-CimInstance -CimClass $eventClass -ClientOnly
    $onNetwork.Enabled = $true
    $onNetwork.Delay = 'PT10S'
    $onNetwork.Subscription = '<QueryList><Query Id="0" Path="Microsoft-Windows-NetworkProfile/Operational"><Select Path="Microsoft-Windows-NetworkProfile/Operational">*[System[(EventID=10000 or EventID=10001)]]</Select></Query></QueryList>'
    $taskSettings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable -MultipleInstances IgnoreNew -ExecutionTimeLimit (New-TimeSpan -Minutes 5) -Priority 7
    Register-ScheduledTask -TaskName 'RelayMCP-Controller' -Description 'RelayMCP: turns remote access (SSH + the RelayMCP agent) on at home and off everywhere else; repairs it at home. See C:\ProgramData\RelayMCP.' -Action $taskAction -Trigger @($atBoot, $atLogon, $every15, $onNetwork) -Settings $taskSettings -User 'SYSTEM' -RunLevel Highest -Force | Out-Null

    Step 'Repair shortcut (Desktop and Start > All apps)'
    $shell = New-Object -ComObject WScript.Shell
    $psExe = Join-Path $env:SystemRoot 'System32\WindowsPowerShell\v1.0\powershell.exe'
    $lnkArgs = '-NoProfile -ExecutionPolicy Bypass -File "' + (Join-Path $KitDir 'Relay-Setup.ps1') + '"'
    foreach ($folder in @([Environment]::GetFolderPath('Desktop'), [Environment]::GetFolderPath('CommonPrograms'))) {
        if (-not $folder) { continue }
        $lnkPath = Join-Path $folder 'Repair RelayMCP.lnk'
        $lnk = $shell.CreateShortcut($lnkPath)
        $lnk.TargetPath = $psExe
        $lnk.Arguments = $lnkArgs
        $lnk.WorkingDirectory = $KitDir
        $lnk.IconLocation = "$env:SystemRoot\System32\imageres.dll,73"
        $lnk.Description = "Re-enable remote control from $HostLabel (RelayMCP; works at home only)"
        $lnk.Save()
        $bytes = [System.IO.File]::ReadAllBytes($lnkPath)
        $bytes[0x15] = $bytes[0x15] -bor 0x20
        [System.IO.File]::WriteAllBytes($lnkPath, $bytes)
    }

    $askExe = Join-Path $hhVenv 'Scripts\relaymcp-ask.exe'
    if ($hhInstalled -and (Test-Path $askExe)) {
        Step "'Ask Copilot' voice shortcut (Desktop and Start > All apps)"
        $askIcon = Join-Path $hhVenv 'Lib\site-packages\relaymcp\device\assets\ask-copilot.ico'
        foreach ($folder in @([Environment]::GetFolderPath('Desktop'), [Environment]::GetFolderPath('Programs'))) {
            if (-not $folder) { continue }
            $lnk = $shell.CreateShortcut((Join-Path $folder 'Ask Copilot.lnk'))
            $lnk.TargetPath = $askExe
            $lnk.WorkingDirectory = Split-Path $askExe
            if (Test-Path $askIcon) { $lnk.IconLocation = "$askIcon,0" }
            $lnk.Description = 'Talk to your AI agent: tap, then speak (or hold View + Menu on the controller)'
            $lnk.Save()
        }
        $voiceShortcut = $true
    }

    Step 'Applying home/away state'
    $lastRun = (Get-ScheduledTaskInfo -TaskName 'RelayMCP-Controller').LastRunTime
    Start-ScheduledTask -TaskName 'RelayMCP-Controller'
    for ($i = 0; $i -lt 120; $i++) {
        Start-Sleep -Milliseconds 500
        if (((Get-ScheduledTaskInfo -TaskName 'RelayMCP-Controller').LastRunTime -ne $lastRun) -and ((Get-ScheduledTask -TaskName 'RelayMCP-Controller').State -ne 'Running')) { break }
    }
    $mode = [string](Get-Content (Join-Path $KitDir 'state.txt') -ErrorAction SilentlyContinue | Select-Object -First 1)
    $atHome = ($mode -eq 'home') -and ($homeNets.Count -gt 0)
    $listening = { [bool](Get-NetTCPConnection -LocalPort $ScreenPort -State Listen -ErrorAction SilentlyContinue) }
    if ($atHome) {
        for ($i = 0; ($i -lt 40) -and -not (& $listening); $i++) { Start-Sleep -Milliseconds 500 }
        $hhUp = { [bool](Get-NetTCPConnection -LocalPort $HardwarePort -State Listen -ErrorAction SilentlyContinue) }
        for ($i = 0; $hhInstalled -and ($i -lt 60) -and -not (& $hhUp); $i++) { Start-Sleep -Milliseconds 500 }
        $results.Add("At home ('$($homeNets[0].Network)'): remote access is ON")
        $results.Add("SSH: $((Get-Service sshd).Status), key-only, local network only")
        $results.Add('Screen control: ' + $(if (& $listening) { 'running (hidden)' } else { 'starting' }))
        if ($hhInstalled) { $results.Add('Hardware tools: ' + $(if (& $hhUp) { 'running (hidden)' } else { 'starting' })) }
        $results.Add('Keep-awake: only while an AI agent is using the handheld')
        if ($voiceShortcut) { $results.Add("Voice prompts: hold View + Menu, or tap 'Ask Copilot'") }
    } elseif (-not $gateways.Count) {
        $results.Add('No network right now. Remote access switches off after 10 minutes offline')
        $results.Add("and back on by itself when you're home on $($HomeNetworkNames -join ' / ').")
    } else {
        $results.Add('Away from home: remote access is OFF (SSH, screen control and hardware tools stopped)')
        $results.Add("It turns back on by itself when you're home on $($HomeNetworkNames -join ' / ').")
    }
    $results.Add("Repair shortcut: 'Repair RelayMCP' on the Desktop and in Start > All apps")

    if ($atHome) {
        $hostKey = ((Get-Content (Join-Path $SshDir 'ssh_host_ed25519_key.pub') -TotalCount 1) -split ' ')[0..1] -join ' '
        $ip = (Get-NetIPAddress -AddressFamily IPv4 -InterfaceIndex $homeNets[0].InterfaceIndex -ErrorAction SilentlyContinue | Where-Object { $_.IPAddress -notlike '169.254.*' } | Select-Object -First 1).IPAddress
        Send-Report ([ordered]@{ status = 'ok'; name = $DeviceName; version = $RelayVersion; user = $env:USERNAME; host = $env:COMPUTERNAME; ip = $ip; hostkey = $hostKey; mcp = (& $listening); gateway = (($homeNets | ForEach-Object { $_.Mac }) -join ',') })
        $summary = "All set! Your AI agent on $HostLabel can reach this handheld while it's at home.`n`n" + ($results -join "`n")
    } else {
        $summary = "All set. You're not on your home network right now, so remote access is off or switching off.`n`n" + ($results -join "`n")
    }
    Write-Host ''
    Write-Host $summary -ForegroundColor Green
    Show-Result $summary $true
} catch {
    $message = $_.Exception.Message
    Write-Host "Setup failed: $message" -ForegroundColor Red
    if ($atHome) { Send-Report ([ordered]@{ status = 'error'; name = $DeviceName; user = $env:USERNAME; host = $env:COMPUTERNAME; error = $message }) }
    Show-Result "Setup hit a problem:`n`n$message`n`nLog: $setupLog" $false
    if ($Unattended) { $global:LASTEXITCODE = 1 }
} finally {
    if ($transcribing) { try { Stop-Transcript | Out-Null } catch { } }
}
